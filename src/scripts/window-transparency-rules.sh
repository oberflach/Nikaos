#!/usr/bin/env bash
# Writes the Super+G per-app transparency into a Hyprland config file so it
# survives `hyprctl reload`, fullscreen and reboots. The overlay card's live
# rules only last for the session; this is the persistent copy.
# Rules match non-fullscreen windows only, so fullscreen shows the app
# opaque and the opacity comes back on exit.
# Kitty and Vesktop are skipped: window-transparency.sh makes their own
# backgrounds translucent, and a compositor rule would fade their text too.
set -euo pipefail

settings="${XDG_CONFIG_HOME:-$HOME/.config}/serpantinum/settings.json"
out="${XDG_CONFIG_HOME:-$HOME/.config}/hypr/config/transparency.lua"

# The overlay card passes its {class: percent} map as $1 and the blur
# switch (on|off) as $2, so a value it just saved does not race the
# settings.json write; run with no argument to rebuild from settings.json.
#
# Blur: off -> Hyprland blurs nothing (windows and the shell layers).
# On -> only windows with a saved transparency below 100% are blurred
# (opaque windows skip the blur pass entirely), plus the shell layers.
#
# Game mode (GameMode.qml) writes its Hyprland flags, a comma list of
# opaque,noBlur,noAnim,scanout,vrr, to $state/game_flags; they override
# the above while set.
state="${XDG_STATE_HOME:-$HOME/.local/state}/serpantinum"
flags="$(cat "$state/game_flags" 2>/dev/null || true)"
has() { [[ ",$flags," == *",$1,"* ]]; }

if [ $# -gt 0 ]; then
    blur="${2:-}"
    [ -n "$blur" ] || blur=$(jq -r 'if .windowBlur == false then "off" else "on" end' "$settings" 2>/dev/null || echo on)
    input="{\"windowTransparency\": $1, \"windowBlur\": $([ "$blur" = off ] && echo false || echo true)}"
else
    input="$(cat "$settings")"
fi
has opaque && input="$(jq -c '.windowTransparency = {}' <<< "$input")"
has noBlur && input="$(jq -c '.windowBlur = false' <<< "$input")"

{
    echo "-- Generated by serpantinum (window-transparency-rules.sh) from the"
    echo "-- Super+G transparency card. Do not edit: it is rewritten on change."
    jq -r '
        (.windowTransparency // {}) | to_entries[]
        | select(.key != "kitty" and .key != "vesktop")
        | select((.value | type) == "number" and .value >= 30 and .value < 100)
        | "hl.window_rule({ match = { class = [[(?i)^"
          + (.key | gsub("(?<c>[.^$*+?()\\[\\]{}|\\\\])"; "\\\(.c)"))
          + "$]], fullscreen = false }, opacity = " + ((.value / 100) | tostring) + " })"
    ' <<< "$input"
    if [ "$(jq -r '.windowBlur' <<< "$input")" = "false" ]; then
        echo "-- Blur switched off in the Super+G card."
        echo "hl.config({ decoration = { blur = { enabled = false } } })"
    else
        echo "-- Blur only behind transparent windows: the last matching rule wins."
        echo "hl.config({ decoration = { blur = { enabled = true } } })"
        echo "hl.window_rule({ match = { class = [[.*]] }, no_blur = true })"
        jq -r '
            (.windowTransparency // {}) | to_entries[]
            | select((.value | type) == "number" and .value >= 30 and .value < 100)
            | "hl.window_rule({ match = { class = [[(?i)^"
              + (.key | gsub("(?<c>[.^$*+?()\\[\\]{}|\\\\])"; "\\\(.c)"))
              + "$]] }, no_blur = false })"
        ' <<< "$input"
        echo 'hl.layer_rule({ name = "serpantinum-blur", match = { namespace = "^(quickshell|qs-master|qs-floating-overlay)$" }, blur = true, ignore_alpha = 0.15 })'
    fi
    if [ -n "$flags" ]; then
        echo "-- Game mode: $flags"
        has noAnim && echo "hl.config({ animations = { enabled = false } })"
        has scanout && echo "hl.config({ render = { direct_scanout = 1 } })"
        has vrr && echo "hl.config({ misc = { vrr = 2 } })"
    fi
    true
} > "$out.tmp"
mv -f "$out.tmp" "$out"
